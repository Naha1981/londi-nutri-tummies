async function main() {
  const existing = await db.recipe.count();
  if (existing > 0) {
    console.log(`Recipes already seeded (${existing}). Skipping.`);
    return;
  }
  for (const r of RECIPES) {
    await db.recipe.create({
      data: {
        slug: r.slug,
        title: r.title,
        category: r.category,
        cuisine: "South African",
        minutes: r.minutes,
        servings: r.servings,
        ingredients: JSON.stringify(r.ingredients),
        instructions: JSON.stringify(r.instructions),
        calories: r.calories,
        protein: r.protein,
        carbs: r.carbs,
        fat: r.fat,
        costEst: r.costEst,
        tags: r.tags.join(","),
        allergens: r.allergens.join(","),
        kidApproved: true,
        emoji: r.emoji,
      },
    });
  }
  console.log(`Seeded ${RECIPES.length} recipes.`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(() => db.$disconnect());
